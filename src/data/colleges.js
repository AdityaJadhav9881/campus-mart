export function getCollegeBadge(item) {
  if (item?.code) return `CET ${item.code}`;
  if (item?.type) {
    if (item.type.includes("Autonomous")) return "Autonomous";
    if (item.type.includes("Deemed") || item.type.includes("University")) return "Deemed / University";
    if (item.type.includes("Premier") || item.type.includes("IIT") || item.type.includes("NIT")) return "Premier";
    if (item.type.includes("Medical")) return "Medical";
    return item.type;
  }
  return "Verified Campus";
}

export function fallbackSearchColleges(query = "") {
  const q = (query || "").trim().toLowerCase();
  if (!q) {
    return MAHARASHTRA_CET_COLLEGES.slice(0, 16).map((c) => ({
      ...c,
      badge: getCollegeBadge(c),
      source: "local",
    }));
  }

  const terms = q.split(/\s+/).filter(Boolean);

  const matched = MAHARASHTRA_CET_COLLEGES.map((c) => {
    const haystack = [
      c.code,
      c.name,
      c.shortName,
      c.city,
      c.district,
      c.type,
      c.category,
      ...(Array.isArray(c.aliases) ? c.aliases : []),
    ]
      .filter(Boolean)
      .join(" ")
      .toLowerCase();

    // Every term must be present somewhere in the haystack
    const allMatch = terms.every((term) => haystack.includes(term));
    if (!allMatch) return null;

    let score = 0;
    const lowerName = c.name.toLowerCase();
    const lowerShort = (c.shortName || "").toLowerCase();
    const lowerCity = (c.city || "").toLowerCase();
    const lowerCode = (c.code || "").toLowerCase();

    if (lowerCode === q) score += 120;
    if (lowerShort === q) score += 100;
    if (lowerCity === q) score += 80;
    if (lowerShort.startsWith(q)) score += 60;
    if (lowerName.includes(q)) score += 40;
    if (lowerCity.includes(q)) score += 25;

    return {
      college: {
        ...c,
        badge: getCollegeBadge(c),
        source: "local",
      },
      score,
    };
  })
    .filter(Boolean)
    .sort((a, b) => b.score - a.score)
    .map((item) => item.college);

  return matched.slice(0, 30);
}
